#!/usr/bin/env bash
# ABOUTME: Scans a git diff or a list of files for leaked infrastructure identifiers.
# ABOUTME: Exits non-zero on any unallowlisted match (standards/08-iac.md 'Redaction check').
#
# Scans added lines (diff mode) or whole files (path mode) for shapes that could leak
# district-identifying infrastructure facts: IPv4/IPv6 addresses, CIDRs, 12-digit AWS
# account IDs, AWS ARNs carrying an account number, Route 53 hosted zone IDs, a bare
# VLAN number next to the word "vlan" (not a filename or anchor like "15-onprem...md"),
# hostnames matching a known district domain pattern, and email addresses. The IPv6
# pattern is word-bounded so it can't match hex-shaped fragments inside an unrelated
# word (e.g. "Upgrade::Allowed"). Exits non-zero if anything survives the allowlist.
#
# Usage:
#   redact-check.sh --diff [<base-ref>]   # scan this PR's added lines vs <base-ref> (default: origin/main)
#   redact-check.sh --paths <path> [<path> ...]
#   redact-check.sh <path> [<path> ...]   # shorthand for --paths
#
# Allowlist: policy/redaction/allow.txt, one entry per line.
#   - A bare line is matched as a literal substring of the matched text.
#   - A line prefixed "re:" is an extended regex matched against the matched text.
#   - Blank lines and lines starting with "#" are ignored.
# Hostname deny patterns: policy/redaction/hostname-patterns.txt, one extended-regex
#   fragment per line (e.g. a real internal domain suffix). Blank/"#" lines ignored.
#   Ships empty (comment-only) in this repo — a district fills it in locally and keeps
#   it out of the public repo, same as the environment file (08-iac.md 'Private environment file').

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ALLOW_FILE="${REDACT_ALLOW_FILE:-$SCRIPT_DIR/allow.txt}"
HOSTNAME_FILE="${REDACT_HOSTNAME_FILE:-$SCRIPT_DIR/hostname-patterns.txt}"

mode=""
base_ref="origin/main"
paths=()

if [[ $# -eq 0 ]]; then
  echo "usage: $0 --diff [<base-ref>] | --paths <path>... | <path>..." >&2
  exit 2
fi

case "$1" in
  --diff)
    mode="diff"
    shift
    if [[ $# -gt 0 ]]; then
      base_ref="$1"
      shift
    fi
    ;;
  --paths)
    mode="paths"
    shift
    paths=("$@")
    ;;
  *)
    mode="paths"
    paths=("$@")
    ;;
esac

# --- pattern definitions -----------------------------------------------------
# Three parallel arrays (name, extended-regex, ignore-case) rather than one
# delimited string, because several of these regexes contain a literal "|".
pattern_names=(
  ipv4
  ipv6
  aws-account-id
  aws-arn
  hosted-zone-id
  vlan-number
  email
)
pattern_regexes=(
  '([0-9]{1,3}\.){3}[0-9]{1,3}(/[0-9]{1,2})?'
  '\b([0-9a-fA-F]{0,4}:){2,7}[0-9a-fA-F]{0,4}\b'
  '[^0-9]([0-9]{12})[^0-9]'
  'arn:aws[a-zA-Z0-9-]*:[a-zA-Z0-9-]+:[a-zA-Z0-9-]*:[0-9]{12}:[a-zA-Z0-9/:_-]*'
  '(/hostedzone/Z|zone[ _]?id["'"'"'[:space:]]*[:=]?["'"'"'[:space:]]*Z)[0-9A-Z]{10,32}'
  'vlan[^0-9]{0,20}[0-9]{1,4}([^0-9-]|$)'
  '[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}'
)
pattern_ignorecase=(0 1 0 0 1 1 0)

# --- allowlist / hostname-deny loaders ---------------------------------------
allow_literals=()
allow_regexes=()
if [[ -f "$ALLOW_FILE" ]]; then
  while IFS= read -r line; do
    [[ -z "$line" || "$line" == \#* ]] && continue
    if [[ "$line" == re:* ]]; then
      allow_regexes+=("${line#re:}")
    else
      allow_literals+=("$line")
    fi
  done < "$ALLOW_FILE"
fi

hostname_patterns=()
if [[ -f "$HOSTNAME_FILE" ]]; then
  while IFS= read -r line; do
    [[ -z "$line" || "$line" == \#* ]] && continue
    hostname_patterns+=("$line")
  done < "$HOSTNAME_FILE"
fi

is_allowed() {
  local matched="$1"
  local lit re
  for lit in "${allow_literals[@]+"${allow_literals[@]}"}"; do
    [[ -n "$lit" && "$matched" == *"$lit"* ]] && return 0
  done
  for re in "${allow_regexes[@]+"${allow_regexes[@]}"}"; do
    [[ -n "$re" ]] || continue
    if [[ "$matched" =~ $re ]]; then
      return 0
    fi
  done
  return 1
}

findings=0

scan_line() {
  local file="$1" lineno="$2" content="$3"
  local name regex ic matched_text idx

  # a committed .terraform.lock.hcl line is a provider package hash
  # ("zh:<64 hex chars>"), which can coincidentally contain 12 consecutive
  # digits; it's generated by `tofu init`, never a real identifier.
  if [[ "$content" =~ \"zh:[0-9a-f]{64}\",?[[:space:]]*$ ]]; then
    return
  fi

  for idx in "${!pattern_names[@]}"; do
    name="${pattern_names[$idx]}"
    regex="${pattern_regexes[$idx]}"
    ic="${pattern_ignorecase[$idx]}"
    if [[ "$ic" == "1" ]]; then
      matched_text=$(grep -oE -i -- "$regex" <<< "$content" || true)
    else
      matched_text=$(grep -oE -- "$regex" <<< "$content" || true)
    fi
    [[ -z "$matched_text" ]] && continue
    while IFS= read -r m; do
      [[ -z "$m" ]] && continue
      # the account-id pattern brackets the 12 digits with non-digit guard
      # characters so it doesn't also match inside a longer digit run; strip
      # those guards back off before reporting/allowlisting.
      if [[ "$name" == "aws-account-id" ]]; then
        m="${m#?}"
        m="${m%?}"
      fi
      # the vlan-number pattern brackets the digits with a trailing non-digit,
      # non-hyphen guard so it doesn't also match a number that's really part
      # of a filename or section anchor (e.g. "(15-onprem-platform.md"); that
      # guard char is captured only when it exists (not at end of line), so
      # strip it back off only when the match doesn't already end in a digit.
      if [[ "$name" == "vlan-number" ]]; then
        if [[ "$m" != *[0-9] ]]; then
          m="${m%?}"
        fi
      fi
      # require at least one hex digit, and then either "::" or both a
      # digit and a hex letter, so this doesn't fire on a bare "::" (Go
      # module source syntax, CloudFormation resource types), an all-digit
      # colon-joined value like a systemd OnCalendar time ("03:00:00"), or a
      # short all-letter run ("not:a:real:thing").
      if [[ "$name" == "ipv6" ]]; then
        if [[ ! "$m" =~ [0-9a-fA-F] ]]; then
          continue
        fi
        # fewer than three hex characters cannot be an address ("::e" in a
        # shell snippet, "3:::" inside an S3 ARN).
        hexchars="${m//[^0-9a-fA-F]/}"
        if (( ${#hexchars} < 3 )); then
          continue
        fi
        if [[ "$m" != *"::"* ]]; then
          if [[ "$m" != *[0-9]* ]] || [[ ! "$m" =~ [a-fA-F] ]]; then
            continue
          fi
        fi
        # an AWS-owned ARN (a published managed policy, a service-linked
        # role) carries an empty region field and a literal account field of
        # just the partition name, which shapes like an IPv6 address once the
        # two empty-field colons land next to each other. Not a leak.
        if [[ "$content" =~ arn:aws[a-zA-Z0-9-]*:[a-zA-Z0-9-]+:: ]]; then
          continue
        fi
      fi
      if is_allowed "$m"; then
        continue
      fi
      echo "REDACTION: $file:$lineno: $name: $m"
      findings=$((findings + 1))
    done <<< "$matched_text"
  done

  for hp in "${hostname_patterns[@]+"${hostname_patterns[@]}"}"; do
    matched_text=$(grep -oE -- "$hp" <<< "$content" || true)
    [[ -z "$matched_text" ]] && continue
    while IFS= read -r m; do
      [[ -z "$m" ]] && continue
      if is_allowed "$m"; then
        continue
      fi
      echo "REDACTION: $file:$lineno: hostname-pattern: $m"
      findings=$((findings + 1))
    done <<< "$matched_text"
  done
}

# --- diff mode ----------------------------------------------------------------
scan_diff() {
  local base="$1"
  local current_file=""
  local lineno=0
  while IFS= read -r line; do
    if [[ "$line" == "+++ "* ]]; then
      current_file="${line#+++ }"
      current_file="${current_file#b/}"
      continue
    fi
    if [[ "$line" == "@@ "* ]]; then
      # @@ -a,b +c,d @@  -> start tracking new-file line numbers at c
      lineno=$(sed -E 's/^@@ -[0-9]+(,[0-9]+)? \+([0-9]+).*/\2/' <<< "$line")
      continue
    fi
    if [[ "$line" == "+"* && "$line" != "+++"* ]]; then
      scan_line "$current_file" "$lineno" "${line#+}"
      lineno=$((lineno + 1))
    elif [[ "$line" != "-"* ]]; then
      lineno=$((lineno + 1))
    fi
  done < <(git diff --unified=0 "$base"...HEAD)
}

# --- path mode ------------------------------------------------------------
# One grep pass per pattern per file (not per line) so this stays fast on a
# whole-repo scan; matches are reported as file:line:pattern:text exactly
# like diff mode.
scan_file() {
  local f="$1"
  local name regex ic idx lineno m flags

  for idx in "${!pattern_names[@]}"; do
    name="${pattern_names[$idx]}"
    regex="${pattern_regexes[$idx]}"
    ic="${pattern_ignorecase[$idx]}"
    [[ "$ic" == "1" ]] && flags="-i" || flags=""
    # blank out committed .terraform.lock.hcl hash lines (see scan_line)
    # without shifting line numbers, so grep -n stays accurate.
    while IFS=: read -r lineno m; do
      [[ -z "$m" ]] && continue
      if [[ "$name" == "aws-account-id" ]]; then
        m="${m#?}"
        m="${m%?}"
      fi
      # the vlan-number pattern brackets the digits with a trailing non-digit,
      # non-hyphen guard so it doesn't also match a number that's really part
      # of a filename or section anchor (e.g. "(15-onprem-platform.md"); that
      # guard char is captured only when it exists (not at end of line), so
      # strip it back off only when the match doesn't already end in a digit.
      if [[ "$name" == "vlan-number" ]]; then
        if [[ "$m" != *[0-9] ]]; then
          m="${m%?}"
        fi
      fi
      # require at least one hex digit, and then either "::" or both a
      # digit and a hex letter, so this doesn't fire on a bare "::" (Go
      # module source syntax, CloudFormation resource types), an all-digit
      # colon-joined value like a systemd OnCalendar time ("03:00:00"), or a
      # short all-letter run ("not:a:real:thing").
      if [[ "$name" == "ipv6" ]]; then
        if [[ ! "$m" =~ [0-9a-fA-F] ]]; then
          continue
        fi
        # fewer than three hex characters cannot be an address ("::e" in a
        # shell snippet, "3:::" inside an S3 ARN).
        hexchars="${m//[^0-9a-fA-F]/}"
        if (( ${#hexchars} < 3 )); then
          continue
        fi
        if [[ "$m" != *"::"* ]]; then
          if [[ "$m" != *[0-9]* ]] || [[ ! "$m" =~ [a-fA-F] ]]; then
            continue
          fi
        fi
        # an AWS-owned ARN (a published managed policy, a service-linked
        # role) carries an empty region field and a literal account field of
        # just the partition name, which shapes like an IPv6 address once the
        # two empty-field colons land next to each other. Not a leak.
        if [[ "$(sed -n "${lineno}p" "$f")" =~ arn:aws[a-zA-Z0-9-]*:[a-zA-Z0-9-]+:: ]]; then
          continue
        fi
      fi
      is_allowed "$m" && continue
      echo "REDACTION: $f:$lineno: $name: $m"
      findings=$((findings + 1))
    done < <(sed -E 's/^([[:space:]]*)"zh:[0-9a-f]{64}",?([[:space:]]*)$//' "$f" \
                | grep -noE $flags -- "$regex" || true)
  done

  for hp in "${hostname_patterns[@]+"${hostname_patterns[@]}"}"; do
    while IFS=: read -r lineno m; do
      [[ -z "$m" ]] && continue
      is_allowed "$m" && continue
      echo "REDACTION: $f:$lineno: hostname-pattern: $m"
      findings=$((findings + 1))
    done < <(grep -noE -- "$hp" "$f" || true)
  done
}

scan_paths() {
  local f
  for f in "${paths[@]}"; do
    [[ -f "$f" ]] || continue
    # skip vendored Terraform provider plugin caches outright: they're
    # `tofu init` output, not authored content, and carry large binaries plus
    # lock-file hashes that coincidentally shape-match an account ID.
    [[ "$f" == *"/.terraform/providers/"* ]] && continue
    # skip remaining binaries: -I makes grep treat one as non-matching
    # instead of reading it line by line.
    grep -Iq . "$f" 2>/dev/null || continue
    scan_file "$f"
  done
}

if [[ "$mode" == "diff" ]]; then
  scan_diff "$base_ref"
else
  if [[ ${#paths[@]} -eq 0 ]]; then
    echo "no paths given" >&2
    exit 2
  fi
  scan_paths
fi

if [[ "$findings" -gt 0 ]]; then
  echo "" >&2
  echo "redact-check: $findings finding(s). Replace real values with <token> placeholders," >&2
  echo "or add a documented, reviewed entry to policy/redaction/allow.txt (08-iac.md 'Redaction check')." >&2
  exit 1
fi

echo "redact-check: clean"
exit 0
